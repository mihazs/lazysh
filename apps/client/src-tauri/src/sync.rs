struct Enrollment {
    config: SyncConfig,
    password: String,
    recovery_key: String,
    settings_etag: Option<String>,
    credentials_etag: Option<String>,
    #[serde(default)]
    settings_revision: u64,
    #[serde(default)]
    credentials_revision: u64,
}
impl Drop for Enrollment {
    fn drop(&mut self) {
        self.password.zeroize();
        self.recovery_key.zeroize();
    }
}
impl Enrollment {
    fn enabled(&self, scope: Scope) -> bool {
        match scope {
            Scope::Settings => self.config.settings_enabled,
            Scope::Credentials => self.config.credentials_enabled,
        }
    }
    fn etag(&self, scope: Scope) -> Option<&str> {
        match scope {
            Scope::Settings => self.settings_etag.as_deref(),
            Scope::Credentials => self.credentials_etag.as_deref(),
        }
    }
    fn set_etag(&mut self, scope: Scope, value: Option<String>) {
        match scope {
            Scope::Settings => self.settings_etag = value,
            Scope::Credentials => self.credentials_etag = value,
        }
    }
    fn recovery(&self) -> Result<Zeroizing<String>> {
        recovery(&self.recovery_key)
    }
    fn revision(&self, scope: Scope) -> u64 {
        match scope {
            Scope::Settings => self.settings_revision,
            Scope::Credentials => self.credentials_revision,
        }
    }
    fn set_revision(&mut self, scope: Scope, value: u64) {
        match scope {
            Scope::Settings => self.settings_revision = value,
            Scope::Credentials => self.credentials_revision = value,
        }
    }
}
