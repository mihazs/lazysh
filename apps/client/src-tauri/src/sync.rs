const ACCOUNT: &str = "sync-enrollment-v1";
const LIMIT: usize = 8 * 1024 * 1024;
const WORK_FACTOR: u8 = 14;
const RECOVERY_PREFIX: &str = "LAZYSH-SYNC-V1-";
fn recovery(value: &str) -> Result<Zeroizing<String>> {
    let encoded = value
        .strip_prefix(RECOVERY_PREFIX)
        .ok_or("Invalid lazysh sync recovery key")?;
    if encoded.len() != 64
        || !encoded
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
    {
        return Err("Recovery keys must be generated by lazysh".into());
    }
    Ok(Zeroizing::new(value.into()))
}
fn generate_recovery() -> Zeroizing<String> {
    let bytes = Zeroizing::new(rand::random::<[u8; 32]>());
    use std::fmt::Write as _;
    let mut value = Zeroizing::new(String::from(RECOVERY_PREFIX));
    for byte in bytes.iter() {
        write!(&mut *value, "{byte:02x}").expect("writing to String cannot fail");
    }
    value
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Scope {
    Settings,
    Credentials,
}
impl Scope {
    fn file(self) -> &'static str {
        match self {
            Self::Settings => "lazysh-settings-v1.age",
            Self::Credentials => "lazysh-credentials-v1.age",
        }
    }
}
