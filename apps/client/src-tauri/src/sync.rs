fn validate_bundle(bundle: &Bundle, scope: Scope) -> Result<()> {
    if bundle.version != 1
        || bundle.revision == 0
        || bundle.scope != scope
        || bundle.hosts.len() > 1000
        || bundle.credentials.len() > 1000
    {
        return Err("Unsupported or oversized sync snapshot".into());
    }
    if bundle.hosts.iter().any(|host| host.biometric_unlock) {
        return Err(
            "Biometric unlock is a device-local policy and cannot be imported through sync".into(),
        );
    }
    if scope == Scope::Settings
        && (!bundle.credentials.is_empty()
            || bundle
                .hosts
                .iter()
                .any(|h| h.fingerprint.is_some() || h.credentials_stored))
    {
        return Err("Settings sync must not contain credentials or host pins".into());
    }
    if scope == Scope::Credentials && bundle.preferences.is_some() {
        return Err("Credential sync must not contain settings".into());
    }
    if let Some(preferences) = &bundle.preferences {
        const ALLOWED: &[&str] = &[
            "version",
            "appTheme",
            "sessionLayout",
            "uiLanguage",
            "cjkFallback",
            "theme",
            "customTheme",
            "customThemeInfo",
            "fontSize",
            "fontFamily",
            "cursorStyle",
            "cursorBlink",
            "scrollback",
            "optionAsMeta",
            "screenReader",
            "toolbar",
            "snippets",
            "chords",
            "pinchZoom",
            "gestures",
            "bodyGestures",
            "gestureChords",
            "dpadCorners",
            "autoHideToolbar",
            "composerSendEnter",
            "dismissKeyboardOnOverscroll",
            "toolbarAlternates",
        ];
        let object = preferences.as_object().ok_or("Invalid sync preferences")?;
        validate_theme_preferences(object)?;
        if object
            .get("sessionLayout")
            .is_some_and(|value| !matches!(value.as_str(), Some("list" | "cards")))
            || object.get("uiLanguage").is_some_and(|value| {
                !matches!(value.as_str(), Some("system" | "en" | "pt-BR" | "es"))
            })
            || object
                .get("dismissKeyboardOnOverscroll")
                .is_some_and(|value| !value.is_boolean())
            || object.get("version").and_then(|v| v.as_u64()) != Some(1)
            || object.keys().any(|key| !ALLOWED.contains(&key.as_str()))
            || serde_json::to_vec(preferences)
                .map_err(|_| "Invalid preferences")?
                .len()
                > 128 * 1024
        {
            return Err("Unsupported sync preferences".into());
        }
    }
    let mut ids = HashSet::new();
    for host in &bundle.hosts {
        host.validate().map_err(|_| "Invalid synced host")?;
        if !ids.insert(&host.id) {
            return Err("Duplicate synced host identity".into());
        }
        if host.fingerprint.as_ref().is_some_and(|pin| {
            !pin.starts_with("SHA256:")
                || pin.len() != 50
                || !pin[7..]
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'+' || b == b'/')
        }) {
            return Err("Invalid synced host fingerprint".into());
        }
    }
    let mut credential_ids = HashSet::new();
    for record in &bundle.credentials {
        if !ids.contains(&record.host_id)
            || !credential_ids.insert(&record.host_id)
            || bundle
                .hosts
                .iter()
                .find(|h| h.id == record.host_id)
                .is_none_or(|h| h.fingerprint.is_none())
            || record
                .credentials
                .password
                .as_ref()
                .is_some_and(|v| v.len() > 65536)
            || record
                .credentials
                .private_key
                .as_ref()
                .is_some_and(|v| v.len() > 65536)
            || record
                .credentials
                .passphrase
                .as_ref()
                .is_some_and(|v| v.len() > 1024)
        {
            return Err("Invalid synced credential record".into());
        }
    }
    Ok(())
}
fn validate_theme_preferences(object: &serde_json::Map<String, serde_json::Value>) -> Result<()> {
    let colors = object
        .get("customTheme")
        .map(|value| value.as_object().ok_or("Invalid imported theme"))
        .transpose()?;
    if let Some(colors) = colors {
        const COLORS: &[&str] = &[
            "background",
            "foreground",
            "cursor",
            "cursorAccent",
            "selectionBackground",
            "selectionForeground",
            "selectionInactiveBackground",
            "black",
            "red",
            "green",
            "yellow",
            "blue",
            "magenta",
            "cyan",
            "white",
            "brightBlack",
            "brightRed",
            "brightGreen",
            "brightYellow",
            "brightBlue",
            "brightMagenta",
            "brightCyan",
            "brightWhite",
            "bold",
        ];
        if !colors.contains_key("background")
            || !colors.contains_key("foreground")
            || colors.iter().any(|(key, value)| {
                !COLORS.contains(&key.as_str())
                    || !value.as_str().is_some_and(|color| {
                        if key == "bold" && color == "bright" {
                            return true;
                        }
                        (if key == "bold" {
                            matches!(color.len(), 4 | 7)
                        } else {
                            matches!(color.len(), 4 | 7 | 9)
                        }) && color.starts_with('#')
                            && color.as_bytes()[1..].iter().all(u8::is_ascii_hexdigit)
                    })
            })
        {
            return Err("Invalid imported theme colors".into());
        }
    }
    if let Some(info) = object.get("customThemeInfo") {
        let info = info.as_object().ok_or("Invalid imported theme metadata")?;
        if info.len() != 2
            || !info
                .get("name")
                .and_then(|v| v.as_str())
                .is_some_and(|name| {
                    !name.trim().is_empty()
                        && name.chars().count() <= 40
                        && !name.chars().any(char::is_control)
                })
            || !matches!(
                info.get("mode").and_then(|v| v.as_str()),
                Some("dark" | "light")
            )
            || colors.is_none()
        {
            return Err("Invalid imported theme metadata".into());
        }
        for key in ["background", "foreground"] {
            let color = colors.unwrap()[key].as_str().unwrap();
            if color.len() == 9 && !color.to_ascii_lowercase().ends_with("ff") {
                return Err("Whole-app theme colors must be opaque".into());
            }
        }
    }
    if object.get("appTheme").and_then(|v| v.as_str()) == Some("custom")
        && (colors.is_none() || !object.contains_key("customThemeInfo"))
    {
        return Err("Custom app theme requires validated metadata and colors".into());
    }
    if object.get("theme").and_then(|v| v.as_str()) == Some("custom") && colors.is_none() {
        return Err("Custom terminal theme requires colors".into());
    }
    Ok(())
}

fn encrypt(key: &str, bundle: &Bundle) -> Result<Vec<u8>> {
    validate_bundle(bundle, bundle.scope)?;
    let bytes =
        Zeroizing::new(serde_json::to_vec(bundle).map_err(|_| "Cannot encode sync snapshot")?);
    if bytes.len() > LIMIT - 4096 {
        return Err("Sync snapshot exceeds the size limit".into());
    }
    encrypt_bytes(key, &bytes)
}
fn encrypt_bytes(key: &str, bytes: &[u8]) -> Result<Vec<u8>> {
    // A shared-secret age recipient also authenticates key possession; public-key age does not.
    let mut recipient =
        age::scrypt::Recipient::new(age::secrecy::SecretString::from(recovery(key)?.to_string()));
    recipient.set_work_factor(WORK_FACTOR);
    let encryptor =
        age::Encryptor::with_recipients(std::iter::once(&recipient as &dyn age::Recipient))
            .map_err(|_| "Cannot initialize snapshot encryption")?;
    let mut encrypted = Vec::new();
    let mut writer = encryptor
        .wrap_output(&mut encrypted)
        .map_err(|_| "Cannot encrypt sync snapshot")?;
    writer
        .write_all(bytes)
        .map_err(|_| "Cannot encrypt sync snapshot")?;
    writer
        .finish()
        .map_err(|_| "Cannot finish sync encryption")?;
    Ok(encrypted)
}
fn decrypt(key: &str, bytes: &[u8], scope: Scope) -> Result<Bundle> {
    let plaintext = decrypt_bytes(key, bytes)?;
    let bundle: Bundle =
        serde_json::from_slice(&plaintext).map_err(|_| "Invalid encrypted sync snapshot")?;
    validate_bundle(&bundle, scope)?;
    Ok(bundle)
}
fn decrypt_bytes(key: &str, bytes: &[u8]) -> Result<Zeroizing<Vec<u8>>> {
    if bytes.len() > LIMIT {
        return Err("Encrypted sync data exceeds 8 MiB".into());
    }
    let mut identity =
        age::scrypt::Identity::new(age::secrecy::SecretString::from(recovery(key)?.to_string()));
    identity.set_max_work_factor(WORK_FACTOR);
    let decryptor = age::Decryptor::new(bytes).map_err(|_| "Invalid encrypted sync file")?;
    let reader = decryptor
        .decrypt(std::iter::once(&identity as &dyn age::Identity))
        .map_err(|_| "Cannot decrypt sync data. Check your recovery key and endpoint.")?;
    let mut plaintext = Zeroizing::new(Vec::new());
    reader
        .take((LIMIT + 1) as u64)
        .read_to_end(&mut plaintext)
        .map_err(|_| "Encrypted snapshot is corrupted or truncated")?;
    if plaintext.len() > LIMIT {
        return Err("Decrypted snapshot exceeds the size limit".into());
    }
    Ok(plaintext)
}
fn same_identity(a: &Host, b: &Host) -> bool {
    a.hostname == b.hostname
        && a.port == b.port
        && a.username == b.username
        && a.jump_host_id == b.jump_host_id
        && a.forward_agent == b.forward_agent
}
fn merge_remote(mut local: Bundle, remote: Option<Bundle>) -> Result<Bundle> {
    let Some(remote) = remote else {
        return Ok(local);
    };
    if remote.scope != local.scope || remote.revision >= local.revision {
        return Err(
            "Remote revision conflicts with this device. Fetch and review it first.".into(),
        );
    }
    for host in remote.hosts {
        match local.hosts.iter_mut().find(|h| h.id == host.id) {
            Some(saved) => {
                if !same_identity(saved, &host)
                    || (saved.fingerprint.is_some()
                        && host.fingerprint.is_some()
                        && saved.fingerprint != host.fingerprint)
                {
                    return Err("Remote host identity conflicts with this device. Resolve the profile before uploading.".into());
                }
                if saved.fingerprint.is_none() {
                    saved.fingerprint = host.fingerprint;
                }
            }
            None => local.hosts.push(host),
        }
    }
    for record in remote.credentials {
        if !local
            .credentials
            .iter()
            .any(|r| r.host_id == record.host_id)
        {
            local.credentials.push(record);
        }
    }
    validate_bundle(&local, local.scope)?;
    Ok(local)
}
fn plan(
    bundle: &Bundle,
    local: &[Host],
) -> (Vec<Host>, HashSet<String>, Vec<PreviewHost>, Vec<Conflict>) {
    let mut additions = Vec::new();
    let mut credential_ids = HashSet::new();
    let mut hosts = Vec::new();
    let mut conflicts = Vec::new();
    for remote in &bundle.hosts {
        let saved = local.iter().find(|h| h.id == remote.id);
        let has_credentials = bundle.credentials.iter().any(|r| r.host_id == remote.id);
        let conflict = if saved.is_some_and(|h| !same_identity(h, remote)) {
            Some("The local host address, user or route differs")
        } else if saved.is_some_and(|h| {
            h.fingerprint.is_some()
                && remote.fingerprint.is_some()
                && h.fingerprint != remote.fingerprint
        }) {
            Some("The local verified host pin differs; sync will not replace it")
        } else if has_credentials && saved.is_some_and(|h| h.credentials_stored) {
            Some("Local saved credentials are preserved")
        } else if local.iter().any(|h| {
            h.hostname == remote.hostname
                && h.port == remote.port
                && remote.fingerprint.is_some()
                && h.fingerprint.is_some()
                && h.fingerprint != remote.fingerprint
        }) {
            Some("Another local profile has a different verified pin for this address")
        } else {
            None
        };
        if let Some(reason) = conflict {
            conflicts.push(Conflict {
                id: remote.id.clone(),
                reason: reason.into(),
            });
            continue;
        }
        if saved.is_none() {
            let mut host = remote.clone();
            host.credentials_stored = false;
            host.biometric_unlock = false;
            additions.push(host);
        }
        if has_credentials {
            credential_ids.insert(remote.id.clone());
        }
        hosts.push(PreviewHost {
            id: remote.id.clone(),
            name: remote.name.clone(),
            hostname: remote.hostname.clone(),
            port: remote.port,
            username: remote.username.clone(),
            jump_host_id: remote.jump_host_id.clone(),
            forward_agent: remote.forward_agent,
            fingerprint: remote.fingerprint.clone(),
            add_host: saved.is_none(),
            import_credentials: has_credentials,
            trust_fingerprint: remote.fingerprint.is_some()
                && !local.iter().any(|h| {
                    h.hostname == remote.hostname
                        && h.port == remote.port
                        && h.fingerprint == remote.fingerprint
                }),
        });
    }
    (additions, credential_ids, hosts, conflicts)
}

