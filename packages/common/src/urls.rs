/// Parsed HTTPS boundary only. Callers retain raw-input and path policy.
pub fn credential_free_https(url: &url::Url) -> bool {
    url.scheme() == "https"
        && url.host_str().is_some()
        && url.username().is_empty()
        && url.password().is_none()
        && url.query().is_none()
        && url.fragment().is_none()
}
